CREATE DATABASE IF NOT EXISTS mysite
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE mysite;

CREATE TABLE IF NOT EXISTS profile (
  id INT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  english_name VARCHAR(100) NOT NULL,
  avatar VARCHAR(512) NOT NULL,
  introduction TEXT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS projects (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  english VARCHAR(255) NOT NULL,
  summary TEXT NOT NULL,
  description TEXT NOT NULL,
  image VARCHAR(512) NOT NULL,
  features TEXT NOT NULL,
  related_route VARCHAR(512) NOT NULL,
  related_label VARCHAR(255) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS photo_albums (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  subtitle VARCHAR(255) NOT NULL,
  description TEXT,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS photos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  album_id INT UNSIGNED NOT NULL,
  src VARCHAR(512) NOT NULL,
  alt VARCHAR(512) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_photos_album
    FOREIGN KEY (album_id) REFERENCES photo_albums (id)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  UNIQUE KEY photo_source (album_id, src)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS calligraphy_works (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  src VARCHAR(512) NOT NULL,
  alt VARCHAR(512) NOT NULL,
  ratio VARCHAR(30) NOT NULL,
  description TEXT,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
